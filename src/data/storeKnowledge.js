export function exportJarvisMemoryAsJSON() {
  const knowledge = getStoreKnowledge();
  const dataStr = 'data:text/json;charset=utf-8,' + encodeURIComponent(JSON.stringify(knowledge, null, 2));
  const downloadAnchor = document.createElement('a');
  downloadAnchor.setAttribute('href', dataStr);
  downloadAnchor.setAttribute('download', `deco_vintage_jarvis_memory_${new Date().toISOString().slice(0, 10)}.json`);
  document.body.appendChild(downloadAnchor);
  downloadAnchor.click();
  downloadAnchor.remove();
}

export function importJarvisMemoryFromJSON(jsonData) {
  try {
    const parsed = typeof jsonData === 'string' ? JSON.parse(jsonData) : jsonData;
    if (parsed && typeof parsed === 'object') {
      saveStoreKnowledge(parsed);
      return true;
    }
  } catch (e) {
    console.error('Failed to import Jarvis memory:', e);
  }
  return false;
}

