const KNOWLEDGE_STORAGE_KEY = 'deco_jarvis_knowledge_v2';

export function getStoreKnowledge() {
  try {
    if (typeof localStorage !== 'undefined') {
      const stored = localStorage.getItem(KNOWLEDGE_STORAGE_KEY);
      if (stored) {
        const parsed = JSON.parse(stored);
        if (parsed && typeof parsed === 'object') {
          return {
            ...DEFAULT_STORE_KNOWLEDGE,
            ...parsed,
            customDocuments: parsed.customDocuments || DEFAULT_STORE_KNOWLEDGE.customDocuments || [],
            referenceImages: parsed.referenceImages || DEFAULT_STORE_KNOWLEDGE.referenceImages || [],
            ownerDirectives: parsed.ownerDirectives || DEFAULT_STORE_KNOWLEDGE.ownerDirectives || [],
            quickPrompts: parsed.quickPrompts || DEFAULT_STORE_KNOWLEDGE.quickPrompts || DEFAULT_STORE_KNOWLEDGE.quickActions || []
          };
        }
      }
    }
  } catch (e) {
    console.warn('[storeKnowledge] Fallback to default knowledge memory:', e);
  }
  return DEFAULT_STORE_KNOWLEDGE;
}

import { getAuthToken } from '../utils/apiClient.js';

// Auto-hydrate from VPS SSD / PostgreSQL backend on startup
if (typeof window !== 'undefined') {
  fetch('/api/jarvis')
    .then(r => r.ok ? r.json() : null)
    .then(serverData => {
      if (serverData && typeof serverData === 'object' && Object.keys(serverData).length > 0) {
        localStorage.setItem(KNOWLEDGE_STORAGE_KEY, JSON.stringify(serverData));
        window.dispatchEvent(new CustomEvent('deco-jarvis-knowledge-updated', { detail: serverData }));
        console.log('[Deco JARVIS] Memoria sincronizada desde backend PostgreSQL.');
      }
    })
    .catch((err) => {
      console.warn('[Deco JARVIS] Fallback a memoria local:', err);
    });
}

export function saveStoreKnowledge(knowledge) {
  try {
    if (typeof localStorage !== 'undefined') {
      const payload = {
        ...knowledge,
        updatedAt: new Date().toISOString()
      };

      localStorage.setItem(KNOWLEDGE_STORAGE_KEY, JSON.stringify(payload));
      window.dispatchEvent(new CustomEvent('deco-jarvis-knowledge-updated', { detail: payload }));

      // Save to VPS Backend PostgreSQL
      const token = getAuthToken();
      fetch('/api/jarvis/save', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          ...(token ? { 'Authorization': `Bearer ${token}` } : {})
        },
        body: JSON.stringify(payload)
      }).catch((err) => {
        console.error('[storeKnowledge] Error guardando en backend:', err);
      });

      return true;
    }
  } catch (e) {
    console.error('[storeKnowledge] Error al guardar memoria:', e);
    return false;
  }
  return false;
}

export function addCustomDocument(doc) {
  const current = getStoreKnowledge();
  const docs = current.customDocuments || [];
  const newDoc = {
    id: `doc-${Date.now()}`,
    title: doc.title || 'Documento sin título',
    category: doc.category || 'General',
    content: doc.content || '',
    dateAdded: new Date().toLocaleDateString('es-GT')
  };
  docs.push(newDoc);
  current.customDocuments = docs;
  current.updatedAt = new Date().toISOString();
  return saveStoreKnowledge(current);
}

export function updateCustomDocument(doc) {
  const current = getStoreKnowledge();
  current.customDocuments = (current.customDocuments || []).map(d => d.id === doc.id ? { ...d, ...doc } : d);
  current.updatedAt = new Date().toISOString();
  return saveStoreKnowledge(current);
}

export function deleteCustomDocument(id) {
  const current = getStoreKnowledge();
  current.customDocuments = (current.customDocuments || []).filter(d => d.id !== id);
  current.updatedAt = new Date().toISOString();
  return saveStoreKnowledge(current);
}

export const removeCustomDocument = deleteCustomDocument;

